"""Generate a documented mixture of fictional quantitative-trait GWAS summaries."""
from pathlib import Path
import json
import numpy as np
import pandas as pd
from scipy.stats import norm

ROOT=Path(__file__).resolve().parents[2]


def main():
    rng=np.random.default_rng(27112026)
    m=22000;maximum_n=20000
    # Varied invented spans, not GRCh37/38 chromosome lengths.
    spans=np.rint(np.linspace(215,42,22)*1e6+rng.uniform(-4e6,4e6,22)).astype(int)
    density=spans*rng.uniform(.8,1.2,22)
    counts=rng.multinomial(m-360,density/density.sum())
    regions=[(3,int(spans[2]*.35),.12),(8,int(spans[7]*.62),-.14),(15,int(spans[14]*.48),.11)]
    chrom=[];position=[]
    for c,count in enumerate(counts,1):
        positions=set()
        while len(positions)<count:positions.update(rng.integers(1000,spans[c-1]+1,size=count-len(positions)).tolist())
        for rc,centre,_ in regions:
            if rc==c:
                added=set()
                while len(added)<120:
                    candidate=int(rng.integers(centre-600000,centre+600001))
                    if candidate not in positions:added.add(candidate)
                positions.update(added)
        values=sorted(positions);chrom.extend([c]*len(values));position.extend(values)
    chrom=np.array(chrom);position=np.array(position)
    assert len(position)==m
    # Rare/common mixture chosen for teaching, not fitted to a human population.
    low=rng.random(m)<.45
    maf=np.where(low,.0005+.0795*rng.beta(.45,2.2,m),.01+.49*rng.beta(1.2,1.5,m))
    lower_coverage=rng.random(m)<.18
    n=np.rint(np.where(lower_coverage,11000+8000*rng.beta(2,2,m),maximum_n-1200*rng.beta(2,25,m))
              -700*np.exp(-maf/.008)).astype(int)
    info=np.clip(.94+.055*rng.beta(8,2,m)-.13*np.exp(-maf/.02)+rng.normal(0,.012,m),.3,1)
    poor=rng.random(m)<.035;info[poor]=rng.uniform(.4,.79,int(poor.sum()))
    # Smooth distance-dependent correlation in latent noise, not estimated LD.
    noise=np.empty(m)
    for i in range(m):
        rho=0.0 if i==0 or chrom[i]!=chrom[i-1] else np.exp(-(position[i]-position[i-1])/50000)
        noise[i]=rng.normal() if rho==0 else rho*noise[i-1]+np.sqrt(1-rho*rho)*rng.normal()
    true_effect=np.zeros(m)
    for c,centre,amplitude in regions:
        ix=chrom==c
        true_effect[ix]+=amplitude*np.exp(-.5*((position[ix]-centre)/120000)**2)
    se=1/np.sqrt(2*n*maf*(1-maf)*info)
    beta_minor=true_effect+noise*se
    # Reverse both effect sign and allele frequency consistently when the named
    # effect allele is the major allele. MAF and p-values are invariant to this.
    flip=rng.random(m)<.5
    beta=np.where(flip,-beta_minor,beta_minor)
    eaf=np.where(flip,1-maf,maf)
    minor=rng.choice(list('ACGT'),m)
    major=np.array([rng.choice([base for base in 'ACGT' if base!=a]) for a in minor])
    effect=np.where(flip,major,minor);other=np.where(flip,minor,major)
    beta[0],se[0],eaf[0],info[0],n[0]=.12,.02,.25,.98,20000
    effect[0],other[0]='A','G'
    truth_role=np.where(true_effect!=0,'simulated_signal_profile','background')
    truth_role[0]='fixed_reference'
    p=2*norm.sf(np.abs(beta/se))
    table=pd.DataFrame(dict(variant_id=[f'SYN{i:06d}' for i in range(1,m+1)],chromosome=chrom,
        position=position,effect_allele=effect,other_allele=other,beta=beta,standard_error=se,
        p_value=p,effect_allele_frequency=eaf,sample_size=n,imputation_info=info))
    folder=ROOT/'data/synthetic';folder.mkdir(parents=True,exist_ok=True)
    table.to_csv(folder/'summary-statistics.tsv',sep='\t',index=False,float_format='%.15g')
    metadata=dict(study_id='CDI_SYNTHETIC_GWAS_V2',trait='Fictional standardized quantitative trait',
        population='Synthetic mixture; not fitted to any human population',genome_build='SYNTHETIC',
        effect_type='beta',effect_units='standardized fictional trait units per effect allele',
        summary_scope='genome_wide',source='Generated by scripts/python/prepare_synthetic.py',synthetic=True,
        seed=27112026,variant_count=m,maximum_simulated_sample_size=maximum_n,
        sample_size_description='Most variants near nominal N=20000, with a smaller lower-coverage component; N is simulated, not actual people.',
        simulation_notes=['Varied invented chromosome spans and density; three locally denser signal regions.',
            'Low-frequency/common MAF mixture; INFO and coverage can be lower at low MAF.',
            'SE depends on N, MAF and INFO except the fixed verification row.',
            'Local latent noise correlation and smooth effect profiles illustrate clusters; neither is a real LD matrix.',
            'Effect alleles are simulated major or minor alleles with consistent sign and EAF orientation.',
            'SYN000001 keeps beta=.12, SE=.02, EAF=.25, INFO=.98, N=20000 as a fixed verification row.',
            'This is a teaching simulation, not an empirical GWAS benchmark or fitted genotype model.'])
    (folder/'study-metadata.json').write_text(json.dumps(metadata,indent=2)+'\n')
    truth=pd.DataFrame(dict(variant_id=table.variant_id,role=truth_role,minor_allele=minor,major_allele=major,
        effect_allele_is_major=flip,latent_noise=noise,true_effect_per_minor_allele=true_effect,
        lower_coverage_component=lower_coverage))
    truth.loc[0,'lower_coverage_component']=False
    truth.loc[0,['minor_allele','major_allele','effect_allele_is_major','true_effect_per_minor_allele','latent_noise']]=['A','G',False,.12,0]
    truth.to_csv(ROOT/'data/provenance/synthetic-truth.tsv',sep='\t',index=False)
    pd.DataFrame({'chromosome':range(1,23),'invented_span_bp':spans,'variant_rows':np.bincount(chrom)[1:]}).to_csv(ROOT/'data/provenance/synthetic-layout.tsv',sep='\t',index=False)
    pd.DataFrame(regions,columns=['chromosome','invented_centre_bp','effect_profile_amplitude']).to_csv(ROOT/'data/provenance/synthetic-regions.tsv',sep='\t',index=False)
    print(f'Prepared v2: {m:,} fictional variant rows across 22 varied synthetic chromosome spans.')

if __name__=='__main__':main()
